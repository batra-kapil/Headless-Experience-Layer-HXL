#!/usr/bin/env node
/*
 * Reads IMAGE_BASE_URL from the top of README.md and applies it to the demo fleet:
 *   1. rewrites Image_URL__c in data/Rental_Vehicle__c.json (for a fresh `sf data import tree`)
 *   2. writes scripts/apex/update-image-urls.apex (to update records that are already imported)
 *
 * Usage: node scripts/apply-image-base-url.js
 * Then, for an org that already has the records:
 *   sf apex run --file scripts/apex/update-image-urls.apex --target-org HXL
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const readme = fs.readFileSync(path.join(root, 'README.md'), 'utf8');
const match = readme.match(/^IMAGE_BASE_URL=(\S+)\s*$/m);
if (!match) {
    console.error('IMAGE_BASE_URL=<url> line not found in README.md');
    process.exit(1);
}
const baseUrl = match[1].replace(/\/+$/, '');

const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

const dataPath = path.join(root, 'data', 'Rental_Vehicle__c.json');
const data = JSON.parse(fs.readFileSync(dataPath, 'utf8'));
for (const record of data.records) {
    record.Image_URL__c = `${baseUrl}/${slug(record.Name)}.jpg`;
}
fs.writeFileSync(dataPath, JSON.stringify(data, null, 4) + '\n');

const urlsByName = data.records.map((r) => `    '${r.Name}' => '${r.Image_URL__c}'`).join(',\n');
const apex = `// Generated by scripts/apply-image-base-url.js. Updates Image_URL__c on existing demo records.
Map<String, String> urlsByName = new Map<String, String>{
${urlsByName}
};
List<Rental_Vehicle__c> vehicles = [SELECT Id, Name FROM Rental_Vehicle__c WHERE Name IN :urlsByName.keySet()];
for (Rental_Vehicle__c vehicle : vehicles) {
    vehicle.Image_URL__c = urlsByName.get(vehicle.Name);
}
update vehicles;
System.debug('Updated ' + vehicles.size() + ' vehicles');
`;
fs.writeFileSync(path.join(root, 'scripts', 'apex', 'update-image-urls.apex'), apex);

console.log(`Applied IMAGE_BASE_URL=${baseUrl} to ${data.records.length} records`);
